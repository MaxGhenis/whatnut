def _cache(
    tmp_path, title="Nut consumption and risk of cardiovascular disease", family="Aune"
) -> Path:
    cache = tmp_path / "crossref"
    cache.mkdir(exist_ok=True)
    record = {
        "DOI": SOURCE["doi"],
        "title": [title],
        "author": [{"family": family, "given": "D", "sequence": "first"}],
    }
    (cache / "10.1186_s12916-016-0730-3.json").write_text(
        json.dumps(record), encoding="utf-8"
    )
    (cache / "MANIFEST.json").write_text("{}", encoding="utf-8")
    return cache


