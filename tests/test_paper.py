def _evidence(tmp_path, rows) -> Path:
    import yaml

    path = tmp_path / "evidence.yaml"
    path.write_text(yaml.safe_dump(rows, allow_unicode=True), encoding="utf-8")
    return path


SOURCE = {
    "key": "aune2016nut",
    "doi": "10.1186/s12916-016-0730-3",
    "first_author": "Aune",
    "authors": "Aune D, Keum N",
    "title": "Nut consumption and risk of cardiovascular disease",
    "journal": "BMC Medicine",
    "year": 2016,
    "volume": "14",
    "issue": "1",
    "pages": "207",
    "pmid": "27916000",
}


def test_build_bib_dedupes_and_is_deterministic(tmp_path):
    other = dict(
        SOURCE, key="zzz2020", doi="10.1/zzz", title="Another", authors="Zed A"
    )
    rows = [
        {"id": "r1", "source": SOURCE},
        {"id": "r2", "source": dict(SOURCE)},
        {"id": "r3", "source": other},
    ]
    bib = build_bib.build(_evidence(tmp_path, rows), tmp_path / "none.bib", tmp_path)
    assert build_bib.bib_keys(bib) == ["aune2016nut", "zzz2020"]
    assert "  number       = {1}," in bib and "  date         = {2016}," in bib
    assert (
        "  title        = {{Nut consumption and risk of cardiovascular disease}},"
        in bib
    )
    assert (
        build_bib.build(
            _evidence(tmp_path, list(reversed(rows))), tmp_path / "none.bib", tmp_path
        )
        == bib
    )


