def _merge(parts: Iterable[tuple[str, Mapping]]) -> dict:
    out: dict = {}
    for builder, part in parts:
        for name, v in part.items():
            if name in out:
                raise FillError(f"{builder} redefines {name!r}")
            out[name] = v
    return out


def build_values(r) -> dict[str, Value]:
    values = _merge((b.__name__, b(r)) for b in VALUE_BUILDERS)
    for name, v in values.items():
        if not NAME_RE.fullmatch(name):
            raise FillError(
                f"bad value name {name!r}: use lowercase letters, digits, underscores"
            )
        if not isinstance(v, Value):
            raise FillError(
                f"VALUES[{name!r}] is {type(v).__name__}; "
                "wrap it in a formatter (days, years, pct, ...)"
            )
    return values


def build_tables(r) -> dict[str, str]:
    tables = _merge((b.__name__, b(r)) for b in TABLE_BUILDERS)
    for name, t in tables.items():
        if not NAME_RE.fullmatch(name):
            raise FillError(f"bad table name {name!r}")
        if not isinstance(t, str) or not t.strip():
            raise FillError(f"TABLES[{name!r}] is empty or not a string")
        if "{{" in t:
            raise FillError(f"TABLES[{name!r}] contains '{{{{'")
    return tables


# --------------------------------------------------------------------------
# Template filling and validation.
# --------------------------------------------------------------------------

NAME_RE = re.compile(r"[a-z][a-z0-9_]*")
TABLE_LINE_RE = re.compile(r"^\{\{table:([a-z][a-z0-9_]*)\}\}[ \t]*$", re.M)
SCALAR_RE = re.compile(r"\{\{([a-z][a-z0-9_]*)\}\}")
ENGINE_CELL_RE = re.compile(
    r"^[ \t]*(`{3,}|~{3,})[ \t]*\{[ \t]*(?!=)[A-Za-z]", re.M
)  # ```{python}, not ```{=html}
INLINE_ENGINE_RE = re.compile(r"`\{[A-Za-z]+\}")  # `{python} x`, `{r} x`
FIGURE_RE = re.compile(r"!\[[^\]]*\]\(([^)\s]+)")


def _line_of(text: str, pos: int) -> int:
    return text.count("\n", 0, pos) + 1


def _where(text: str, pattern: re.Pattern, name: str) -> str:
    lines = sorted(
        {
            _line_of(text, m.start())
            for m in pattern.finditer(text)
            if m.group(1) == name
        }
    )
    return f"line {', '.join(map(str, lines))}"


def fill(template: str, values: Mapping[str, Value], tables: Mapping[str, str]) -> str:
    """Substitute values and tables; raise FillError on any mismatch."""
    stray = [
        m
        for m in re.finditer(r"\{\{table:", template)
        if not TABLE_LINE_RE.match(template, template.rfind("\n", 0, m.start()) + 1)
    ]
    if stray:
        lines = ", ".join(str(_line_of(template, m.start())) for m in stray)
        raise FillError(f"{{{{table:...}}}} must sit alone on its line (line {lines})")

    used_tables = set(TABLE_LINE_RE.findall(template))
    used_values = set(SCALAR_RE.findall(template))
    problems = []
    for name in sorted(used_values - set(values)):
        problems.append(
            f"placeholder {{{{{name}}}}} has no value "
            f"({_where(template, SCALAR_RE, name)})"
        )
    for name in sorted(used_tables - set(tables)):
        problems.append(
            f"placeholder {{{{table:{name}}}}} has no table "
            f"({_where(template, TABLE_LINE_RE, name)})"
        )
    for name in sorted(set(values) - used_values):
        problems.append(f"VALUES[{name!r}] is never used in the template")
    for name in sorted(set(tables) - used_tables):
        problems.append(f"TABLES[{name!r}] is never used in the template")
    if problems:
        raise FillError("template and values disagree:\n  " + "\n  ".join(problems))

    out = TABLE_LINE_RE.sub(lambda m: tables[m.group(1)], template)
    out = SCALAR_RE.sub(lambda m: values[m.group(1)].text, out)
    return _add_notice(out)


def _add_notice(text: str) -> str:
    if text.startswith("---\n"):
        return f"---\n# {GENERATED_NOTICE}\n{text[4:]}"
    return f"<!-- {GENERATED_NOTICE} -->\n\n{text}"


def problems_in_filled(text: str) -> list[str]:
    """What a filled manuscript must never contain. Empty list = clean."""
    found = []
    for m in ENGINE_CELL_RE.finditer(text):
        found.append(f"line {_line_of(text, m.start())}: executable code cell")
    for m in INLINE_ENGINE_RE.finditer(text):
        found.append(
            f"line {_line_of(text, m.start())}: inline executable code {m.group(0)!r}"
        )
    for m in re.finditer(r"\{\{", text):
        found.append(
            f"line {_line_of(text, m.start())}: "
            "leftover '{{' (unfilled placeholder or shortcode)"
        )
    return found


def missing_figures(text: str, base: Path = PAPER) -> list[str]:
    """Local image links whose file does not exist."""
    out = []
    for m in FIGURE_RE.finditer(text):
        target = m.group(1)
        if re.match(r"[a-z][a-z0-9+.-]*:", target):  # http:, data:, ...
            continue
        if not (base / target).is_file():
            out.append(f"line {_line_of(text, m.start())}: {target}")
    return out


# Pandoc citation keys: [@key], [@a; @b, p. 3], @key in running text, -@key.
# Cross-references (@fig-x, @tbl-x, @sec-x, @eq-x ...) and e-mail addresses are not
# citations.
CITE_RE = re.compile(
    r"(?<![A-Za-z0-9_.@\-])-?@([A-Za-z0-9_][A-Za-z0-9_:.#$%&+?<>~/\-]*)"
)
CROSSREF_PREFIXES = (
    "fig-",
    "tbl-",
    "sec-",
    "eq-",
    "lst-",
    "thm-",
    "lem-",
    "cor-",
    "prp-",
    "cnj-",
    "def-",
    "exm-",
    "exr-",
    "rem-",
    "sol-",
)


def citation_keys(text: str) -> set[str]:
    """Bibliography keys cited in a Quarto markdown document."""
    body = re.sub(r"\A---\n.*?\n---\n", "", text, flags=re.S)  # front matter
    body = re.sub(r"^(`{3,}|~{3,}).*?^\1", "", body, flags=re.S | re.M)  # fenced code
    body = re.sub(r"`[^`\n]*`", "", body)  # inline code
    body = re.sub(r"<!--.*?-->", "", body, flags=re.S)
    keys = set()
    for m in CITE_RE.finditer(body):
        key = m.group(1).rstrip(".:;,?")
        if key and not key.startswith(CROSSREF_PREFIXES):
            keys.add(key)
    return keys


