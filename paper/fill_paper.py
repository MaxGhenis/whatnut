    cal = r["calibration"]
    st = cal["strata"]
    overall = _row("schwingshackl2021_rrr_overall")
    analog = st["calibrated_analog"]
    cs = [x["linear"]["c_point"] for x in st.values()]
    sens = r["sensitivity"]["calibrations"]
